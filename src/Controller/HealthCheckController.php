<?php

namespace App\Controller;

use Doctrine\Common\Proxy\AbstractProxyFactory;
use Doctrine\ORM\EntityManagerInterface;
use Doctrine\Persistence\Proxy;
use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Annotation\Route;

class HealthCheckController extends AbstractController
{
    public function __construct(
        private readonly EntityManagerInterface $entityManager,
    )
    {
    }

    #[Route('/health/live', name: 'app_health_liveness')]
    public function live(): Response
    {
        $status = match ($this->areDoctrineProxiesHealthy()) {
            true => Response::HTTP_OK,
            false => Response::HTTP_INTERNAL_SERVER_ERROR,
        };

        return new Response(status: $status);
    }

    #[Route('/health/ready', name: 'app_health_readiness')]
    public function ready(): Response
    {
        $status = match ($this->isDatabaseConnectionWorking()) {
            true => Response::HTTP_OK,
            false => Response::HTTP_INTERNAL_SERVER_ERROR,
        };

        return new Response(status: $status);
    }

    private function isDatabaseConnectionWorking(): bool
    {
        try {
            $connection = $this->entityManager->getConnection();
            $return = $connection->fetchOne('SELECT 1');
            if ($return === 1) {
                return true;
            }
        } catch (\Throwable) {
            return false;
        }

        return false;
    }

    /**
     * We had problems with Doctrine Proxy classes not existing in the past, so this check is needed for restart.
     */
    private function areDoctrineProxiesHealthy(): bool
    {
        $autoGenerate = $this->entityManager->getConfiguration()->getAutoGenerateProxyClasses();
        if ($autoGenerate === AbstractProxyFactory::AUTOGENERATE_ALWAYS) {
            // if classes are being autogenerated we can't check them, so let's assume it's ok
            return true;
        }

        try {
            $proxyDir = $this->entityManager->getConfiguration()->getProxyDir();
            if (!is_dir($proxyDir) || !is_readable($proxyDir)) {
                return false;
            }

            $allMetadata = $this->entityManager->getMetadataFactory()->getAllMetadata();

            foreach ($allMetadata as $classMetadata) {
                if (
                    $classMetadata->isMappedSuperclass
                    || $classMetadata->isEmbeddedClass
                    || $classMetadata->getReflectionClass()->isAbstract()
                ) {
                    continue;
                }

                $proxyFile = rtrim($proxyDir, DIRECTORY_SEPARATOR)
                    . DIRECTORY_SEPARATOR
                    . Proxy::MARKER
                    . str_replace('\\', '', $classMetadata->getName())
                    . '.php';

                if (!is_file($proxyFile) || !is_readable($proxyFile)) {
                    return false;
                }

                require_once $proxyFile; // catches broken/unloadable proxy files
            }
        } catch (\Throwable) {
            return false;
        }

        return true;
    }
}
